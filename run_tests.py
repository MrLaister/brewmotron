def check_test_environment():
    """Check if test environment is properly set up."""
    print("Checking test environment setup...")

    issues = []

    # Check Python version
    if sys.version_info < (3, 9):
        issues.append(
            f"Python 3.9+ required, found {sys.version_info.major}.{sys.version_info.minor}"
        )

    # Check if requirements file exists
    if not Path("requirements-test.txt").exists():
        issues.append("requirements-test.txt not found")

    # Check if test directory exists
    if not Path("tests").exists():
        issues.append("tests directory not found")

    # Check if pytest is available
    try:
        subprocess.run(
            [sys.executable, "-m", "pytest", "--version"],
            capture_output=True,
            check=True,
        )
    except (subprocess.CalledProcessError, FileNotFoundError):
        issues.append("pytest not available")

    if issues:
        print("Issues found:")
        for issue in issues:
            print(f"  - {issue}")
        return 1
    else:
        print("Test environment looks good!")
        return 0


def main():
    """Main entry point."""
    parser = argparse.ArgumentParser(
        description="Brewmotron Test Runner",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  %(prog)s unit                    # Run unit tests
  %(prog)s unit -v                 # Run unit tests with verbose output
  %(prog)s integration             # Run integration tests  
  %(prog)s hardware                # Run hardware simulation tests
  %(prog)s all                     # Run all tests
  %(prog)s all --fast              # Run all tests except slow ones
  %(prog)s lint                    # Run code quality checks
  %(prog)s security                # Run security checks
  %(prog)s report                  # Generate test reports
  %(prog)s check                   # Check test environment setup
  %(prog)s install                 # Install test dependencies
        """,
    )

    parser.add_argument(
        "command",
        choices=[
            "unit",
            "integration",
            "hardware",
            "performance",
            "all",
            "lint",
            "security",
            "report",
            "check",
            "install",
        ],
        help="Test command to run",
    )

    parser.add_argument(
        "-v", "--verbose", action="store_true", help="Enable verbose output"
    )

    parser.add_argument(
        "--fast", action="store_true", help="Skip slow tests (for 'all' command)"
    )

    parser.add_argument(
        "--no-cov",
        action="store_true",
        help="Disable coverage reporting (for 'unit' command)",
    )

    parser.add_argument(
        "-k", "--pattern", help="Run tests matching pattern (for 'unit' command)"
    )

    args = parser.parse_args()

    # Change to script directory
    os.chdir(Path(__file__).parent)

    # Route to appropriate function
    if args.command == "unit":
        return run_unit_tests(
            verbose=args.verbose, coverage=not args.no_cov, pattern=args.pattern
        )
    elif args.command == "integration":
        return run_integration_tests(verbose=args.verbose)
    elif args.command == "hardware":
        return run_hardware_tests(verbose=args.verbose)
    elif args.command == "performance":
        return run_performance_tests(verbose=args.verbose)
    elif args.command == "all":
        return run_all_tests(verbose=args.verbose, fast=args.fast)
    elif args.command == "lint":
        return run_lint_checks()
    elif args.command == "security":
        return run_security_checks()
    elif args.command == "report":
        return generate_test_report()
    elif args.command == "check":
        return check_test_environment()
    elif args.command == "install":
        return install_dependencies()
    else:
        parser.print_help()
        return 1


if __name__ == "__main__":
    sys.exit(main())
