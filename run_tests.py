def run_lint_checks() -> int:
    """Run code quality checks."""
    print("\n" + "=" * 60)
    print("Running Code Quality Checks")
    print("=" * 60)

    # Check if tools are available
    tools = ["black", "flake8", "isort"]
    missing_tools = []

    for tool in tools:
        try:
            subprocess.run([tool, "--version"], capture_output=True, check=True)
        except (subprocess.CalledProcessError, FileNotFoundError):
            missing_tools.append(tool)

    if missing_tools:
        print(f"Missing tools: {', '.join(missing_tools)}")
        print("Install them with: pip install black flake8 isort")
        return 1

    # Run Black
    black_result = run_command(
        ["black", "--check", "--diff", "--color", "."],
        "Black Code Formatting Check",
        check=False,
    )

    # Run isort
    isort_result = run_command(
        ["isort", "--check-only", "--diff", "--color", "."],
        "Import Sorting Check",
        check=False,
    )

    # Run flake8
    flake8_result = run_command(
        [
            "flake8",
            ".",
            "--count",
            "--select=E9,F63,F7,F82",
            "--show-source",
            "--statistics",
        ],
        "Flake8 Critical Issues",
        check=False,
    )

    flake8_all_result = run_command(
        [
            "flake8",
            ".",
            "--count",
            "--exit-zero",
            "--max-complexity=10",
            "--max-line-length=127",
            "--statistics",
        ],
        "Flake8 All Issues",
        check=False,
    )

    # Return worst result
    return max(black_result, isort_result, flake8_result)


